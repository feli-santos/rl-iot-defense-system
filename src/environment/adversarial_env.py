    def reset(
        self,
        *,
        seed: Optional[int] = None,
        options: Optional[dict[str, Any]] = None,
    ) -> tuple[np.ndarray, dict[str, Any]]:
        """Reset the environment to start a new episode.

        Args:
            seed: Random seed for reproducibility.
            options: Additional options (unused).

        Returns:
            Tuple of (observation, info).
        """
        super().reset(seed=seed)

        # Setup RNG
        if seed is not None:
            self._rng = np.random.default_rng(seed)
            # Also seed the realization engine
            self._realization_engine._rng = np.random.default_rng(seed)
            np.random.seed(seed)
        else:
            self._rng = np.random.default_rng()

        # Reset episode state
        self._step_count = 0
        self._last_action = 0
        self._recent_block = False
        self._first_attack_step = None
        self._compromise_step = None
        self._defender_deescalations = 0
        self._proportional_bonus_paid = 0.0
        self._deescalation_bonus_paid = 0.0
        self._benign_steps = 0
        self._benign_blocks = 0

        # Initialize attack sequence
        # Start with BENIGN or low-level attack
        self._current_attack_stage = 0  # BENIGN
        self._attack_history = [self._current_attack_stage]

        # Initialize observation window with BENIGN features
        self._observation_window = []
        for _ in range(self._config.window_size):
            features = self._realization_engine.sample(
                KillChainStage.BENIGN,
                aliasing_rate=self._config.aliasing_rate,
                session_coherent=self._config.session_coherent,
            )
            self._observation_window.append(features)

        # Build initial observation
        observation = self._build_observation()

        # Build info dict
        info = self._build_info()

        return observation, info

    def step(
        self,
        action: int,
    ) -> tuple[np.ndarray, float, bool, bool, dict[str, Any]]:
        """Execute one environment step.

        Lifecycle (environment-design v2):

        1. **IMPACT step.** If we entered this step already at IMPACT, this is
           the agent's final mitigation turn. Reward depends on action choice;
           the episode terminates regardless.
        2. **Decision-stage reward.** Reward is computed against
           ``decision_stage = previous_attack_stage`` and the IoTWarden
           recommended-action mapping. No dependence on the agent's previous
           action.
        3. **Attack progression.** The Markov attacker samples the next stage.
           When the agent chose BLOCK or ISOLATE at ACCESS+ stages, the env
           overrides this with a defender-driven de-escalation to BENIGN
           (with probability ``p_defender_deescalation``). On a successful
           override, ``defense_success_bonus`` is added to the reward.
        4. **Termination.** The episode terminates only when the new stage is
           IMPACT (the agent will get one final IMPACT step on the next
           call) — but for backwards compatibility we mark ``terminated`` on
           that step too via ``_check_terminated``. Truncation fires at
           ``max_steps``.
        """
        assert self.action_space.contains(action), f"Invalid action: {action}"

        self._step_count += 1
        previous_attack_stage = self._current_attack_stage

        # 1) Final mitigation turn at IMPACT — fixed reward shape, terminate.
        if previous_attack_stage == KillChainStage.IMPACT.value:
            return self._step_at_impact(action)

        # 2) Reward for this step is decided by stage at decision time.
        reward = self._calculate_reward(action, previous_attack_stage)
        self._track_benign_fpr(action, previous_attack_stage)

        # Record whether the defender just applied force, so the attacker can
        # react (evasion-before-commit) when it advances this step.
        self._recent_block = action >= 3  # BLOCK or ISOLATE

        # 3) Advance the attack.
        if self._config.tug_of_war:
            outcome = self._advance_tug_of_war(action, previous_attack_stage)
            if outcome == "defended":
                # Routine in-game de-escalation: rewarded by the small, capped
                # ``reward_deescalation`` term, NOT the large terminal
                # ``defense_success_bonus`` (which is reserved for surviving a
                # terminal IMPACT step). This decouples the dense pushdown signal
                # from terminal-survival accounting and stops de-escalation-count
                # farming from inflating the reward ceiling.
                reward += self._capped_deescalation_bonus()
        else:
            # Legacy v2 dynamics: autonomous Markov advance with a
            # probabilistic defender-driven de-escalation override.
            agent_forced_deescalation = self._maybe_defender_deescalation(
                action, previous_attack_stage
            )
            if agent_forced_deescalation:
                reward += self._config.defense_success_bonus
                outcome = "defended"
            else:
                self._advance_attack()
                outcome = "ongoing"

        # Lifecycle-floor clamp: real-world IMPACT requires time-to-execute.
        # Until the agent has had its grace period, the attacker is not allowed
        # to short-circuit the kill chain by jumping straight to IMPACT.
        # Concretely: any IMPACT transition before ``min_episode_length`` is
        # downgraded to MANEUVER. This both gives the agent a fair chance to
        # learn the multi-stage dynamics *and* matches the IoTWarden-style
        # threat model in which IMPACT is the consummation of MANEUVER, not
        # an instantaneous transition from RECON.
        if (
            self._current_attack_stage == KillChainStage.IMPACT.value
            and self._step_count < self._config.min_episode_length
        ):
            self._current_attack_stage = KillChainStage.MANEUVER.value
            # Keep the history consistent: replace the last entry rather than
            # appending a parallel one (the attacker only sees the visible chain).
            if self._attack_history:
                self._attack_history[-1] = self._current_attack_stage

        # MTTC bookkeeping — see _build_info() for the consumed fields.
        if (
            self._first_attack_step is None
            and self._current_attack_stage != KillChainStage.BENIGN.value
        ):
            self._first_attack_step = self._step_count
        if (
            self._compromise_step is None
            and self._current_attack_stage == KillChainStage.IMPACT.value
        ):
            self._compromise_step = self._step_count

        # 4) Refresh the observation window with a sample drawn from the stage
        # the attacker occupied *before* this transition was decided. Sampling
        # from ``previous_attack_stage`` (not the new stage) removes the
        # post-transition feature leakage: the agent must infer that the
        # attacker moved from the *evidence it accumulates over time*, rather
        # than reading the just-completed transition off the very next
        # observation. Under partial observability this is the realistic
        # condition — the defender never gets an instantaneous, noise-free
        # readout of the attacker's current stage.
        obs_stage = (
            previous_attack_stage
            if self._config.no_post_transition_leak
            else self._current_attack_stage
        )
        new_features = self._realization_engine.sample(
            KillChainStage(obs_stage),
            aliasing_rate=self._config.aliasing_rate,
            session_coherent=self._config.session_coherent,
        )
        self._observation_window.pop(0)
        self._observation_window.append(new_features)
        self._last_action = action

        # Termination: only IMPACT triggers it, and only after the
        # min_episode_length grace period has elapsed (otherwise the agent
        # never sees a multi-stage trajectory).
        impact_arrived = (
            self._current_attack_stage == KillChainStage.IMPACT.value
            and self._step_count >= self._config.min_episode_length
        )
        if impact_arrived and self._config.impact_is_terminal:
            # environment-design frozen contract (default).
            # Apply the terminal IMPACT penalty inline. The kill chain has
            # consummated this step; we do *not* hand the agent a separate
            # "_step_at_impact" turn for OBSERVE/LOG -> the missed defense
            # is precisely what the IMPACT penalty was designed to punish.
            # Strong defenses (BLOCK/ISOLATE) earn the partial mitigation
            # bonus; weak defenses (OBSERVE/LOG) take the missed-impact hit.
            reward -= self._config.impact_penalty
            if action >= 3:
                reward += self._config.defense_success_bonus
                outcome = "impact_mitigated"
            elif action <= 1:
                reward -= self._config.penalty_missed_impact
                outcome = "impact_missed"
            else:
                outcome = "compromised"
            terminated = True
        else:
            # Either IMPACT has not arrived OR impact_is_terminal=False.
            # When False and IMPACT just arrived this step, do NOT terminate
            # and do NOT apply the inline terminal reward — the agent will
            # get an explicit IMPACT-row decision on the *next* step via
            # ``_step_at_impact`` (path 1 at the top of step()). The
            # "ongoing"/"defended" outcome label set above is preserved
            # so the F9 ablation sees this step as a normal pre-IMPACT
            # step that *just happened* to land on IMPACT.
            terminated = False
        truncated = self._step_count >= self._config.max_steps

        # Proximity-coupled prevention: with no finite budget, the defender
        # wins by holding the attacker below IMPACT for the entire horizon.
        # When the episode truncates (max_steps reached) and the kill chain
        # never consummated, award the prevention bonus and label the outcome
        # "prevented" — the line was held. This only fires when no terminal
        # outcome was already set (outcome is still the in-flight label).
        if (
            self._config.proximity_coupled
            and truncated
            and not terminated
            and self._current_attack_stage < KillChainStage.IMPACT.value
            and outcome not in ("prevented", "impact_mitigated", "impact_missed", "compromised")
        ):
            reward += self._config.prevention_bonus
            outcome = "prevented"

        if terminated or truncated:
            reward = self._apply_episode_fpr_penalty(reward)

        observation = self._build_observation()
        info = self._build_info()
        info["outcome"] = outcome
        return observation, reward, terminated, truncated, info

    # ------------------------------------------------------------------ helpers

    def _step_at_impact(self, action: int) -> tuple[np.ndarray, float, bool, bool, dict[str, Any]]:
        """Handle the agent's final mitigation turn while the attack is at IMPACT."""
        action_cost = get_action_cost(action) * self._config.action_cost_scale
        reward = -(self._config.impact_penalty) - action_cost
        if action >= 3:  # BLOCK or ISOLATE — partial mitigation bonus
            reward += self._config.defense_success_bonus
            outcome = "impact_mitigated"
        elif action <= 1:  # OBSERVE or LOG — severe miss at IMPACT
            reward -= self._config.penalty_missed_impact
            outcome = "impact_missed"
        else:
            outcome = "impact_unmitigated"

        new_features = self._realization_engine.sample(
            KillChainStage.IMPACT,
            aliasing_rate=self._config.aliasing_rate,
            session_coherent=self._config.session_coherent,
        )
        self._observation_window.pop(0)
        self._observation_window.append(new_features)
        self._last_action = action
        if self._compromise_step is None:
            self._compromise_step = self._step_count

        reward = self._apply_episode_fpr_penalty(reward)
        observation = self._build_observation()
        info = self._build_info()
        info["outcome"] = outcome
        return observation, reward, True, False, info

    def _apply_episode_fpr_penalty(self, reward: float) -> float:
        """Subtract terminal FPR penalty if fpr_penalty_beta > 0."""
        if self._config.fpr_penalty_beta <= 0.0:
            return reward
        if self._benign_steps == 0:
            return reward
        fpr = self._benign_blocks / self._benign_steps
        return reward - self._config.fpr_penalty_beta * fpr

    def _track_benign_fpr(self, action: int, previous_stage: int) -> None:
        """Increment benign-step / benign-block counters."""
        if previous_stage == KillChainStage.BENIGN.value:
            self._benign_steps += 1
            if action >= 3:  # BLOCK or ISOLATE
                self._benign_blocks += 1

    def _advance_tug_of_war(self, action: int, previous_stage: int) -> str:
        """Advance the attacker under the tug-of-war dynamics (headline, v3).

        The next stage is a function of the proportionality gap between the
        defender's ``action`` and the stage-recommended action. See the
        ``tug_of_war`` config block for the full specification.

        Returns the step outcome label: ``"defended"`` (attacker pushed down a
        rung), ``"ongoing"`` (held or escalated), or ``"benign"`` (attacker
        dormant at BENIGN and not provoked into onset).
        """
        assert self._rng is not None  # invariant after reset
        stage = int(previous_stage)
        recommended = _recommended_action(stage)

        # --- BENIGN: the attacker is dormant but has its *own* initiative to
        # begin the campaign. Onset to RECON happens autonomously with
        # probability ``p_onset`` regardless of the defender's action — the
        # attacker is not waiting to be provoked. A defender over-reaction
        # (gap >= 2, i.e. RESTRICT/BLOCK/ISOLATE on benign traffic) does not
        # accelerate the kill chain here; it is simply wasteful (and penalised
        # by the benign guardrails in the reward). No de-escalation is possible
        # below BENIGN.
        if stage == KillChainStage.BENIGN.value:
            # Multi-rung onset: the attacker may open the campaign at RECON or,
            # less often, directly at ACCESS (a mid-chain start). A single draw
            # partitions [0,1): [0, p_onset) -> RECON, [p_onset, p_onset +
            # p_onset_access) -> ACCESS, remainder -> stay dormant.
            roll = self._rng.random()
            if roll < self._config.p_onset:
                self._current_attack_stage = KillChainStage.RECON.value
                self._attack_history.append(self._current_attack_stage)
                return "ongoing"
            if roll < self._config.p_onset + self._config.p_onset_access:
                self._current_attack_stage = KillChainStage.ACCESS.value
                self._attack_history.append(self._current_attack_stage)
                return "ongoing"
            # Stay benign.
            self._attack_history.append(self._current_attack_stage)
            return "benign"

        # --- Active attack stage (RECON..MANEUVER; IMPACT is handled by
        # _step_at_impact before we get here). The transition is governed by the
        # *signed* force difference d = action - recommended(stage):
        #
        #   d <= -1 (under-force, defender too weak)  -> ESCALATE   w.p. p_up
        #   d ==  0 (proportional, exactly right)     -> DE-ESCALATE w.p. p_down
        #   d >=  1 (over-force, wasteful)            -> HOLD (no climb)
        #
        # Under-defending therefore lets the attacker climb (real, autonomous
        # pressure: a passive defender loses), the exact response pushes it back
        # down, and over-forcing merely stalls it (and is penalised by the
        # benign / proportionality guardrails in the reward).
        d = action - recommended

        if d <= -1:
            # Under-force: the attacker advances toward IMPACT.
            #
            # Proximity-coupled mode (RESTRAIN-style): escalation pressure
            # scales with the attacker's proximity to its goal,
            # lambda = stage / IMPACT. The closer the attacker is to IMPACT the
            # harder an under-forced defender finds it to hold the line, so the
            # defender must become decisive near the end of the chain. With no
            # finite budget, prevention is earned by holding the attacker below
            # IMPACT for the full horizon (awarded at truncation), not by
            # draining a counter. Default (legacy) mode uses a flat p_up.
            p_up_eff = self._config.p_up
            if self._config.proximity_coupled:
                lam = stage / KillChainStage.IMPACT.value
                p_up_eff = self._config.p_up * (
                    self._config.proximity_min_escalation
                    + (1.0 - self._config.proximity_min_escalation) * lam
                )
            if self._rng.random() < p_up_eff:
                self._current_attack_stage = min(KillChainStage.IMPACT.value, stage + 1)
            self._attack_history.append(self._current_attack_stage)
            return "ongoing"

        if d == 0:
            # Proportional force -> probabilistic de-escalation. ISOLATE
            # de-escalates more reliably than BLOCK (real force gradient). On a
            # failed pushdown the attacker simply holds (it never climbs under a
            # correct response).
            p_down = self._config.p_down_isolate if action == 4 else self._config.p_down
            if self._rng.random() < p_down:
                self._current_attack_stage = max(0, stage - 1)
                self._attack_history.append(self._current_attack_stage)
                self._defender_deescalations += 1
                return "defended"
            self._attack_history.append(self._current_attack_stage)
            return "ongoing"

        # d >= 1: over-force -> the attacker holds (stalled, not advanced).
        # Mis-targeted (disproportionately heavy) force stalls the attacker but
        # does not de-escalate it: spraying ISOLATE at a low stage holds the
        # intrusion in place without pushing it down.
        self._attack_history.append(self._current_attack_stage)
        return "ongoing"

    def _capped_deescalation_bonus(self) -> float:
        """Return the reward for one successful in-game de-escalation.

        Yields ``reward_deescalation`` per pushdown but bounds the cumulative
        per-episode contribution at ``deescalation_bonus_cap`` (when set), so a
        policy cannot farm reward simply by racking up a large *count* of routine
        de-escalations. Once the cap is exhausted, further pushdowns earn 0 from
        this term.
        """
        bonus = self._config.reward_deescalation
        cap = self._config.deescalation_bonus_cap
        if cap is not None:
            bonus = min(bonus, max(0.0, cap - self._deescalation_bonus_paid))
        self._deescalation_bonus_paid += bonus
        return bonus

    def _maybe_defender_deescalation(self, action: int, previous_stage: int) -> bool:
        """Return True iff the agent's action forced a stage reset to BENIGN.

        The override fires when the agent picks BLOCK or ISOLATE at an active
        ACCESS+ attack stage and the configured probability allows it. On a
        successful override the env replaces the natural attack progression
        for this step.
        """
        if action < 3:  # OBSERVE / LOG / RESTRICT never trigger
            return False
        if previous_stage < KillChainStage.ACCESS.value:
            return False
        assert self._rng is not None  # invariant after reset
        if self._rng.random() >= self._config.p_defender_deescalation:
            return False
        # Override the natural attacker transition.
        self._current_attack_stage = KillChainStage.BENIGN.value
        self._attack_history.append(self._current_attack_stage)
        self._defender_deescalations += 1
        return True

    def render(self) -> None:
        """Render the environment state."""
        if self._render_mode == "human":
            print(
                f"Step {self._step_count}: "
                f"Attack Stage = {KillChainStage(self._current_attack_stage).name}, "
                f"Last Action = {ACTION_NAMES[self._last_action]}"
            )

    def close(self) -> None:
        """Clean up environment resources."""
        pass

