# =============================================================================
# ACTION SPACE: Force Continuum
# =============================================================================

ACTION_NAMES: list[str] = [
    "OBSERVE",  # Level 0: Passive monitoring
    "LOG",  # Level 1: Enhanced logging
    "RESTRICT",  # Level 2: Partial, reversible mitigation (rate-limit / constrain)
    "BLOCK",  # Level 3: Block connections
    "ISOLATE",  # Level 4: System isolation
]

ACTION_COSTS: list[float] = [
    0.0,  # OBSERVE: No cost
    0.1,  # LOG: Minimal impact
    0.3,  # RESTRICT: Some disruption
    0.5,  # BLOCK: Significant impact
    0.8,  # ISOLATE: Major disruption
]


def get_action_cost(action: int) -> float:
    """Get the cost of a defensive action.

    Args:
        action: Action index (0-4).

    Returns:
        Cost of the action.
    """
    return ACTION_COSTS[action]


def _load_stage_detector(path: Path) -> Any:
    """Load a frozen stage detector from ``path``.

    Supports ``.pt`` (PyTorch :class:`StageDetector`) and ``.joblib``
    (sklearn :class:`RandomForestClassifier`) checkpoints.  Returns an
    object with a ``predict(features_2d) -> stage_ids`` method.
    """
    suffix = path.suffix.lower()
    if suffix == ".pt":
        from src.detector.stage_detector import StageDetector

        det = StageDetector.from_checkpoint(path)
        # wrap so caller sees uniform ``predict``
        return _DetectorWrapper(det.predict)
    if suffix in (".joblib", ".pkl", ".pickle"):
        import joblib

        clf = joblib.load(path)
        return _DetectorWrapper(clf.predict)
    raise ValueError(
        f"Unsupported stage-detector checkpoint format: {path} " f"(expected .pt or .joblib)"
    )


class _DetectorWrapper:
    """Thin wrapper unifying StageDetector.predict and sklearn.predict."""

    def __init__(self, predict_fn):
        self._predict = predict_fn

    def predict(self, X: np.ndarray) -> np.ndarray:
        return self._predict(X)


def get_action_name(action: int) -> str:
    """Get the name of a defensive action.

    Args:
        action: Action index (0-4).

    Returns:
        Name of the action.
    """
    return ACTION_NAMES[action]


# =============================================================================
# RECOMMENDED-ACTION MAPPING (IoTWarden-aligned, see PLAN §3.1 step 2)
# =============================================================================
#
# stage  -> recommended action
#  0  BENIGN     -> 0  OBSERVE
#  1  RECON      -> 1  LOG
#  2  ACCESS     -> 2  RESTRICT
#  3  MANEUVER   -> 3  BLOCK
#  4  IMPACT     -> 4  ISOLATE
#
# This is the canonical mapping used by IoTWarden (Bhattacharjee et al., 2023,
# Fig. 4) and the policy the new reward function grades against. An action
# within ±1 of the recommended level earns ``reward_proportional``; ±2 or
# more earns ``-penalty_disproportionate``.

_RECOMMENDED_ACTION_BY_STAGE: list[int] = [0, 1, 2, 3, 4]


def _recommended_action(stage: int) -> int:
    """Return the IoTWarden-aligned recommended action for ``stage``."""
    return _RECOMMENDED_ACTION_BY_STAGE[stage]


