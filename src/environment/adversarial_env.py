"""
Adversarial IoT Environment for Blue Team Training.

This module implements the Gymnasium environment where the RL agent
(Blue Team) learns to defend against attacks generated by a
first-order Markov attacker over kill-chain stages.

Key Design
----------
- **Hidden state**. The attack stage is *not* directly observable. The agent
  receives a sliding window of realized feature vectors (and, optionally,
  their first-order deltas).
- **Action space**. ``Discrete(5)`` force-continuum:
  ``OBSERVE=0`` < ``LOG=1`` < ``RESTRICT=2`` < ``BLOCK=3`` < ``ISOLATE=4``.
- **Reward**. *Stage-action proportionality* relative to the IoTWarden
  recommended-action mapping (see :func:`_recommended_action`):

      R_t = R_proportional - C_action - P_overreact - P_underreact +
            R_progress_blocked

  This replaces the previous action-vs-previous-action heuristic; see
  ``docs/results/environment/PLAN.md`` (B2 fix).
- **Lifecycle (environment-design v2).**
    - The episode runs for **at least** ``min_episode_length`` steps and at
      most ``max_steps`` (truncation). Choosing BLOCK or ISOLATE on an
      active attack does *not* end the episode anymore.
    - Instead, with probability ``p_defender_deescalation`` (default 0.6),
      the env *resets the attack to BENIGN* on the next step, modeling the
      defender successfully neutralizing the threat. This produces a
      genuine de-escalation signal that the Markov attacker's upper-triangular
      transition matrix cannot generate on its own (B3 fix).
    - When the attack reaches IMPACT, the agent is granted exactly one final
      defensive turn and the episode terminates regardless of
      ``min_episode_length``.
- **MTTC** (Mean Time To Compromise). Tracked per-episode via
  ``info["mttc_steps"]`` and ``info["compromised"]`` (B5 fix).
"""

