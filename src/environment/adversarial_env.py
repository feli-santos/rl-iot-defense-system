    def _advance_attack(self) -> None:
        """Advance attack sequence using generator."""
        # Use generator to predict next attack stage
        if len(self._attack_history) >= 1:
            # Sample next stage from generator
            next_stage = self._generator.sample_next(
                self._attack_history[-5:],  # Use last 5 stages
                temperature=1.0,
            )
            # Non-monotonic stress-test: independently override with a
            # retreat to a random earlier stage (review 2.4.3).
            current_stage = self._current_attack_stage
            if (
                self._config.retreat_prob > 0.0
                and current_stage > 0
                and self._rng is not None
                and self._rng.random() < self._config.retreat_prob
            ):
                next_stage = int(self._rng.integers(0, current_stage))
            self._current_attack_stage = next_stage
            self._attack_history.append(next_stage)

    def _build_observation(self) -> np.ndarray:
        """Build observation from feature window."""
        # Stack window and flatten
        window_array = np.stack(self._observation_window, axis=0)
        if self._config.include_deltas:
            deltas = np.zeros_like(window_array)
            deltas[1:] = window_array[1:] - window_array[:-1]
            window_array = np.concatenate([window_array, deltas], axis=1)
        observation = window_array.flatten().astype(np.float32)
        # Stage-prediction ablation: append one-hot predicted stage
        if self._config.include_stage_pred:
            assert self._stage_detector is not None
            latest_row = self._observation_window[-1].reshape(1, -1)
            pred_stage = int(self._stage_detector.predict(latest_row)[0])
            one_hot = np.zeros(self._config.num_actions, dtype=np.float32)
            one_hot[pred_stage] = 1.0
            observation = np.concatenate([observation, one_hot])
        return observation

    def _build_info(self) -> dict[str, Any]:
        """Build info dictionary including environment-design telemetry.

        New keys (environment-design):

        - ``compromised`` (bool): True iff the attack reached IMPACT this
          episode.
        - ``mttc_steps`` (int | None): Steps from first non-BENIGN observation
          until IMPACT. ``None`` if the attack never started or never
          reached IMPACT.
        - ``defender_deescalations`` (int): How many times the defender
          successfully forced a stage reset to BENIGN this episode.
        - ``recommended_action`` (int): The IoTWarden-aligned recommended
          action for the *current* stage. Useful for downstream logging
          (e.g., proportionality histograms).
        """
        compromised = self._compromise_step is not None
        if compromised and self._first_attack_step is not None:
            mttc_steps: Optional[int] = self._compromise_step - self._first_attack_step
        else:
            mttc_steps = None

        return {
            "attack_stage": self._current_attack_stage,
            "attack_stage_name": KillChainStage(self._current_attack_stage).name,
            "step_count": self._step_count,
            "attack_history": list(self._attack_history),
            "last_action": self._last_action,
            "last_action_name": ACTION_NAMES[self._last_action],
            "compromised": compromised,
            "mttc_steps": mttc_steps,
            "first_attack_step": self._first_attack_step,
            "compromise_step": self._compromise_step,
            "defender_deescalations": self._defender_deescalations,
            "recommended_action": _recommended_action(self._current_attack_stage),
        }

    def _calculate_reward(self, action: int, previous_stage: int) -> float:
        """Reward for one non-IMPACT step.

        New formulation (environment-design, B2 fix). The reward depends *only* on the
        decision-time stage and the action — not on the agent's previous
        action. Components:

        - ``- C_action``: Cost of executing ``action`` (force-continuum scale).
        - Stage-specific guardrails on extreme errors (penalty_overreact_*,
          penalty_block_*, penalty_missed_impact at IMPACT — although the
          IMPACT branch is normally handled by ``_step_at_impact``).
        - ``+ reward_benign_passive`` when the agent picks OBSERVE/LOG on
          truly benign traffic — small but consistent positive signal so
          the "do nothing" baseline does not net to zero.
        - **Proportionality term (the core)**: ``+ reward_proportional`` when
          ``|action - recommended_action(stage)| ≤ 1``, else
          ``- penalty_disproportionate``. This is the policy the agent is
          ultimately graded against.

        Args:
            action: Defensive action taken (0..4).
            previous_stage: Attack stage at decision time (the stage the
                agent saw when it picked ``action``).

        Returns:
            Scalar reward.
        """
        decision_stage = int(previous_stage)
        reward = 0.0

        # 1) Cost of action.
        reward -= get_action_cost(action) * self._config.action_cost_scale

        # 2) Asymmetric guardrails on extreme errors.
        if decision_stage == KillChainStage.BENIGN.value and action >= 2:
            reward -= self._config.penalty_overreact_benign
            if action >= 3:
                reward -= self._config.penalty_block_benign
        elif decision_stage == KillChainStage.RECON.value and action >= 3:
            reward -= self._config.penalty_block_recon
        if decision_stage == KillChainStage.IMPACT.value and action <= 1:
            # Normally _step_at_impact handles IMPACT, but keep a safety
            # net so a pathological caller doesn't escape the penalty.
            reward -= self._config.penalty_missed_impact

        # 3) Positive signal for the canonical "do nothing on benign" case.
        if decision_stage == KillChainStage.BENIGN.value and action <= 1:
            reward += self._config.reward_benign_passive

        # 4) Stage-action proportionality — the new core (B2 fix).
        recommended = _recommended_action(decision_stage)
        proportionality_gap = abs(action - recommended)
        if proportionality_gap <= 1:
            reward += self._config.reward_proportional
        else:
            reward -= self._config.penalty_disproportionate

        return reward
