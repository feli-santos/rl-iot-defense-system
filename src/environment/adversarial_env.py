@dataclass
class AdversarialEnvConfig:
    """Configuration for the Adversarial Environment.

    See ``docs/results/environment/PLAN.md`` for the rationale behind every reward
    constant. Most fields are tunable in Ablation & Robustness (sensitivity ablation); the
    defaults below are the values used to lock the environment-design exit gates.

    Lifecycle attributes
    --------------------
    max_steps:
        Hard cap on episode length. Truncation fires once
        ``step_count >= max_steps``.
    min_episode_length:
        The episode is *guaranteed* to run for at least this many steps. The
        agent cannot end the episode early via BLOCK/ISOLATE; only IMPACT can
        terminate before this many steps. environment-design exit gate G3.2 requires
        median episode length ≥ 15 with random actions.
    p_defender_deescalation:
        On any step where the agent picks BLOCK or ISOLATE *and* the attack
        is currently at ACCESS or above, the env resets the attack to BENIGN
        on the next step with this probability. The remaining probability
        leaves the Markov attacker in charge as usual. ``0.6`` is the default;
        Ablation & Robustness sweeps this value.

    Reward attributes
    -----------------
    action_cost_scale:
        Multiplier applied to ``ACTION_COSTS[action]``. Allows global
        scaling of how "expensive" actions are without rewriting the table.
    reward_proportional:
        Bonus when ``|action − recommended_action(stage)| ≤ 1``. The agent
        gets this every step where it is "close enough" to the
        IoTWarden-mapped recommended action.
    penalty_disproportionate:
        Symmetric penalty when ``|action − recommended_action(stage)| ≥ 2``.
    impact_penalty, penalty_missed_impact:
        Applied on the final IMPACT step. ``impact_penalty`` is unconditional;
        ``penalty_missed_impact`` is added when the agent under-reacts
        (OBSERVE/LOG).
    penalty_overreact_benign, penalty_block_benign, penalty_block_recon:
        Asymmetric penalties for cocked-trigger policies. Kept from v1
        because preliminary calibration confirmed they meaningfully suppress the
        "always-BLOCK" degenerate strategy.
    defense_success_bonus:
        Earned (a) on the IMPACT step when the agent picks BLOCK/ISOLATE,
        and (b) when the env de-escalates from MANEUVER/IMPACT to BENIGN
        because of an agent-driven defense action.
    impact_is_terminal:
        If ``True`` (default, environment-design frozen contract), the episode
        terminates the same step the env transitions to IMPACT, and the
        terminal reward is applied inline against whatever action the
        agent took *that same step* (which was chosen at the previous,
        non-IMPACT stage).

        If ``False`` (ablation D7.3, F9 ablation axis), the env transitions
        to IMPACT but does NOT terminate that step. The agent's *next*
        action is taken as the explicit IMPACT-row decision, then
        :meth:`_step_at_impact` runs with that action and the env
        terminates. This decouples "the step where IMPACT arrives" from
        "the step where the agent picks an IMPACT response", giving the
        agent an unconfounded IMPACT-row decision. Default ``True``
        preserves the environment-design/4/5/6 frozen contract byte-for-byte.
    """

    # Lifecycle
    max_steps: int = 500
    min_episode_length: int = 20
    window_size: int = 5
    include_deltas: bool = True
    num_actions: int = 5
    impact_is_terminal: bool = True

    # =====================================================================
    # Tug-of-war attacker dynamics (environment-design v3, headline)
    # =====================================================================
    # The attacker's stage transition is driven by the *proportionality gap*
    # between the defender's action ``a`` and the stage-recommended action
    # ``rec = recommended(s)``, with ``gap = |a - rec|``:
    #
    #   gap == 0 (correctly calibrated force)  -> attacker DE-ESCALATES
    #                                             s -> max(0, s-1) w.p. p_down
    #   gap == 1 (adjacent / tolerable)        -> attacker HOLDS at s
    #   gap >= 2 (mis-calibrated force)        -> attacker ESCALATES
    #                                             s -> min(IMPACT, s+1) w.p. p_up
    #
    # The residual ``1 - p_*`` mass is a "hold" (nothing happens this step),
    # which deliberately prevents a degenerate, perfectly deterministic
    # lookup-table solution and keeps value planning under partial
    # observability meaningful. This ±1 graded structure mirrors the
    # proportionality reward exactly, so reward and dynamics are
    # self-consistent. ISOLATE (a=4) de-escalates *more reliably* than BLOCK
    # (a=3) — ``p_down_isolate`` >= ``p_down`` — giving the force ladder a
    # real effect gradient (not just a cost gradient) and removing the
    # weakly-dominated-action pathology of the v2 environment.
    #
    # Set ``tug_of_war=False`` to recover the v2 autonomous-Markov +
    # probabilistic-de-escalation dynamics (retained for the legacy ablation).
    tug_of_war: bool = True
    # Multi-rung autonomous onset from BENIGN (the attacker's own initiative,
    # independent of the defender). Each step at BENIGN the attacker opens a
    # campaign at RECON with probability ``p_onset`` or directly at ACCESS with
    # probability ``p_onset_access`` (a mid-chain campaign start); otherwise it
    # stays dormant. Multi-rung onset is what forces even a *correct* defender to
    # exercise ACCESS/MANEUVER-appropriate responses rather than pinning the
    # attacker at RECON and farming the proportional bonus. Set
    # ``p_onset_access=0.0`` to recover strict single-rung (RECON-only) onset,
    # which is retained as the pure-sequential threat-model ablation.
    p_onset: float = 0.35  # P(BENIGN -> RECON) per step
    p_onset_access: float = 0.10  # P(BENIGN -> ACCESS) per step (mid-chain start)
    p_down: float = 0.90  # P(de-escalate | correctly-calibrated force, d==0)
    p_up: float = 0.90  # P(escalate | under-force, d<=-1)
    p_down_isolate: float = 0.98  # P(de-escalate) when the force is ISOLATE (a=4)

    # Legacy v2 de-escalation probability (only used when tug_of_war=False).
    p_defender_deescalation: float = 0.6

    # Non-monotonic attacker stress-test (review 2.4.3)
    # After sampling the next stage from the generator, independently
    # override it with a retreat to a random earlier stage with this
    # probability.  Default 0.0 preserves the monotonic-attacker contract.
    retreat_prob: float = 0.0

    # Evasion-before-commit reactive attacker (the one adaptive-attacker axis).
    # When the defender has *just* applied force (BLOCK/ISOLATE) and the attacker
    # is still at a pre-trigger stage (RECON/ACCESS), it probabilistically stalls
    # (does not progress) in anticipation, with this probability. Unlike
    # ``retreat_prob`` (random, defender-independent) and de-escalation (resets to
    # BENIGN on force at ACCESS+), this is *coupled to the defender's action*.
    # Default 0.0 disables it.
    evasion_prob: float = 0.0

    # Explicit terminal reward for a prevented attack (attacker held below
    # IMPACT for the entire horizon). Calibrated to +50, mirroring the net
    # reward of a correct IMPACT mitigation (-impact_penalty +
    # defense_success_bonus = +50), so the security objective (prevention) and
    # the reward signal are aligned. This closes the latent farming loophole
    # where, with prevention_bonus=0, dragging the episode out to accumulate
    # per-step proportional rewards would be more profitable than ending it
    # early via prevention. The 0-vs-50 contrast is itself a
    # reward-mis-specification ablation cell.
    prevention_bonus: float = 50.0

    # Stage-prediction ablation (review 2.4.1)
    # If non-None, the env loads a frozen stage detector and (optionally)
    # appends its predicted stage to the observation vector.
    stage_detector_path: Optional[str] = None
    include_stage_pred: bool = False

    # Reward — proportionality core (B2 fix)
    action_cost_scale: float = 1.0
    reward_proportional: float = 5.0
    penalty_disproportionate: float = 5.0
    # Per-episode cap on the *cumulative* proportional bonus. Without a cap, a
    # fixed low-force policy can pin the attacker in an early stage where its
    # action is "correct" and farm ``reward_proportional`` every step for the
    # full horizon, inflating reward to oracle-like levels without ever
    # mitigating a real threat. The cap (default +5 x min_episode_length = +100)
    # preserves the early dense learning signal but removes the farming
    # incentive; once exhausted, correct play earns 0 from this term (penalties
    # still apply). ``None`` disables the cap (the uncapped case is itself a
    # reward-mis-specification ablation cell).
    proportional_bonus_cap: Optional[float] = 100.0

    # Reward mode. Two contracts:
    #
    # - ``"coupled"`` (alias ``"proportional"``): kill-chain-aware *shaping*. The
    #   per-step reward includes a proportionality term keyed on
    #   ``d = action - recommended_action(stage)`` — the SAME quantity that
    #   drives the attacker's tug-of-war transition. Under this contract the
    #   value-maximising policy reduces to "infer the stage, emit the matching
    #   action", i.e. a 5-way stage classifier. A supervised detector that acts
    #   on its prediction (RF-Acting) is exactly that classifier and is hard to
    #   beat in-distribution. Retained as the reward-shaping ablation cell.
    #
    # - ``"outcome"`` (alias ``"outcome_only"``): the per-step reward is ONLY the
    #   action cost; every stage-conditioned shaping term (proportionality,
    #   benign/recon guardrails, benign-passive bonus) is stripped. The learning
    #   signal then comes exclusively from realised OUTCOMES applied in
    #   ``step()``/``_step_at_impact``: the capped de-escalation bonus (paid only
    #   on an actual attacker pushdown), the terminal prevention bonus, the
    #   terminal IMPACT penalty/mitigation accounting, and the optional terminal
    #   FPR penalty. The reward is therefore NOT a function of matching the
    #   per-step ``recommended_action(stage)`` label, which de-couples the
    #   objective from the attacker dynamics and removes the privileged-shaping
    #   advantage of a supervised classifier. This is the primary deployment
    #   contract for the re-posed task.
    reward_mode: str = "outcome"

    # Reward — terminal & extreme cases
    impact_penalty: float = 200.0
    penalty_missed_impact: float = 150.0
    # The mitigation bonus is intentionally calibrated so that a *correct*
    # IMPACT response (ISOLATE) net-rewards the agent: -impact_penalty +
    # defense_success_bonus = -200 + 250 = +50. This makes the optimal
    # policy strictly better than the do-nothing baseline and lets the
    # G3.4 exit gate hold (recommended-action mean reward > 0). This bonus is
    # RESERVED for surviving a *terminal* IMPACT step; routine in-game
    # de-escalations are rewarded by the separate, smaller ``reward_deescalation``
    # term below (see PLAN §B6 and the de-escalation-farming fix).
    defense_success_bonus: float = 250.0
    # Per-step reward for a successful in-game de-escalation (pushing the
    # attacker down one kill-chain rung under a proportional response). This is
    # deliberately *decoupled* from ``defense_success_bonus`` (+250, reserved for
    # terminal IMPACT survival): reusing the large terminal bonus for every
    # routine pushdown over-rewards the raw *count* of de-escalations, making
    # "more attacks = more reward" and inflating the oracle ceiling. A small
    # positive value keeps de-escalation worth doing as a dense signal without
    # turning it into a farm. Its cumulative per-episode contribution is bounded
    # by ``deescalation_bonus_cap``.
    reward_deescalation: float = 15.0
    # Per-episode cap on the *cumulative* de-escalation reward (mirrors
    # ``proportional_bonus_cap``). ``None`` disables the cap (the uncapped case is
    # itself a reward-mis-specification ablation cell).
    deescalation_bonus_cap: Optional[float] = 150.0

    # Reward — benign-traffic guardrails
    reward_benign_passive: float = 10.0
    penalty_overreact_benign: float = 50.0
    penalty_block_benign: float = 100.0
    penalty_block_recon: float = 50.0

    # Lagrangian FPR penalty (review 2.2 / Direction 6)
    # At episode end, subtract beta * (benign_blocks / benign_steps).
    # beta=0.0 disables the penalty (default, preserves prior behaviour).
    fpr_penalty_beta: float = 0.0

    # -------------------------------------------------------------------------
    # Partial-observability redesign (sequential-decision re-pose).
    #
    # The legacy environment samples a CICIoT2023 feature row i.i.d. per step,
    # which makes a memoryless supervised classifier (RF-Acting) optimal by
    # construction: every observation fully reveals the stage, so there is no
    # value in integrating evidence over time. The three knobs below restore the
    # partial observability and temporal structure that real IoT intrusion
    # detection exhibits, so that a recurrent belief-state agent can outperform a
    # per-step classifier. All default to the legacy behaviour (byte-compatible).
    #
    # ``aliasing_rate`` (alpha): probability that a step emits a feature row from
    # an ADJACENT kill-chain stage instead of the true stage. A single RECON flow
    # can look benign; a single ACCESS flow can look like RECON. The stage is then
    # only reliably inferable from the *sequence*, not any single observation.
    # Applied identically to every consumer (RL and RF-Acting see the same
    # ambiguous stream), so it confers no information asymmetry. alpha=0 is the
    # legacy fully-observable anchor where the classifier is expected to win.
    aliasing_rate: float = 0.0
    # ``session_coherent``: when True, draw observations as a contiguous,
    # without-replacement run of same-stage rows (a session/campaign proxy) rather
    # than an independent uniform draw each step, so the per-step deltas carry
    # genuine temporal signal instead of being differences of unrelated flows.
    session_coherent: bool = False
    # ``no_post_transition_leak``: when True, the observation refreshed after the
    # attacker moves is drawn from the PRE-transition stage, so the just-happened
    # transition is not revealed one step early. Closes an observation leak that
    # weakened the partial-observability claim.
    no_post_transition_leak: bool = False
    # ``proximity_coupled``: RESTRAIN-style defense-tolerance dynamics that
    # replace the finite intrusion budget. The attacker's escalation pressure
    # scales with its proximity to the goal (lambda = stage / IMPACT): the closer
    # to IMPACT, the harder an under-forced defender finds it to hold the line.
    # Prevention is earned by holding the attacker below IMPACT for the entire
    # horizon (awarded at truncation), not by draining a counter. This removes the
    # "any forcing policy prevents once the budget is small" degeneracy and the
    # "B is cherry-picked" critique.
    proximity_coupled: bool = True
    # Floor on the proximity-scaled under-force escalation probability, as a
    # fraction of ``p_up``. At stage RECON (lambda=0.25) escalation probability is
    # p_up * (proximity_min_escalation + (1-proximity_min_escalation)*lambda);
    # at MANEUVER (lambda=0.75) it is higher. Keeps early-stage escalation
    # non-trivial while making late-stage holding demanding.
    proximity_min_escalation: float = 0.4

    # Canonical reward-mode names and their accepted aliases. ``__post_init__``
    # normalises every alias to its canonical token so the rest of the code only
    # ever compares against the canonical set.
    _REWARD_MODE_ALIASES: ClassVar[dict[str, str]] = {
        "proportional": "coupled",
        "coupled": "coupled",
        "outcome_only": "outcome",
        "outcome": "outcome",
    }

    def __post_init__(self) -> None:
        # Normalise reward-mode aliases and fail fast on a typo. A silently
        # ignored bad ``reward_mode`` would fall through to coupled shaping and
        # corrupt the coupled-vs-decoupled ablation, so this must raise.
        canonical = self._REWARD_MODE_ALIASES.get(self.reward_mode)
        if canonical is None:
            valid = sorted(set(self._REWARD_MODE_ALIASES))
            raise ValueError(
                f"Unknown reward_mode {self.reward_mode!r}; " f"expected one of {valid}."
            )
        self.reward_mode = canonical


