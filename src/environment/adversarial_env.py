"""
Adversarial IoT Environment for Blue Team Training.

This module implements the Gymnasium environment where the RL agent
(Blue Team) learns to defend against attacks generated by the Attack
Sequence Generator (Red Team).

Key Design
----------
- **Hidden state**. The attack stage is *not* directly observable. The agent
  receives a sliding window of realized feature vectors (and, optionally,
  their first-order deltas).
- **Action space**. ``Discrete(5)`` force-continuum:
  ``OBSERVE=0`` < ``LOG=1`` < ``THROTTLE=2`` < ``BLOCK=3`` < ``ISOLATE=4``.
- **Reward**. *Stage-action proportionality* relative to the IoTWarden
  recommended-action mapping (see :func:`_recommended_action`):

      R_t = R_proportional - C_action - P_overreact - P_underreact +
            R_progress_blocked

  This replaces the previous action-vs-previous-action heuristic; see
  ``docs/results/environment/PLAN.md`` (B2 fix).
- **Lifecycle (environment-design v2).**
    - The episode runs for **at least** ``min_episode_length`` steps and at
      most ``max_steps`` (truncation). Choosing BLOCK or ISOLATE on an
      active attack does *not* end the episode anymore.
    - Instead, with probability ``p_defender_deescalation`` (default 0.6),
      the env *resets the attack to BENIGN* on the next step, modeling the
      defender successfully neutralizing the threat. This produces a
      genuine de-escalation signal that the LSTM Red Team's upper-triangular
      transition matrix cannot generate on its own (B3 fix).
    - When the attack reaches IMPACT, the agent is granted exactly one final
      defensive turn and the episode terminates regardless of
      ``min_episode_length``.
- **MTTC** (Mean Time To Compromise). Tracked per-episode via
  ``info["mttc_steps"]`` and ``info["compromised"]`` (B5 fix).
"""

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional, Union

import gymnasium as gym
import numpy as np
import torch
from gymnasium import spaces

from src.generator.attack_sequence_generator import AttackSequenceGenerator
from src.utils.label_mapper import KillChainStage
from src.utils.realization_engine import RealizationEngine

# Optional stage-detector loading (lazy to avoid heavy import when unused)
_StageDetector = Any  # forward ref for type hints

logger = logging.getLogger(__name__)

# =============================================================================
# ACTION SPACE: Force Continuum
# =============================================================================

ACTION_NAMES: list[str] = [
    "OBSERVE",  # Level 0: Passive monitoring
    "LOG",  # Level 1: Enhanced logging
    "THROTTLE",  # Level 2: Rate limiting
    "BLOCK",  # Level 3: Block connections
    "ISOLATE",  # Level 4: System isolation
]

ACTION_COSTS: list[float] = [
    0.0,  # OBSERVE: No cost
    0.1,  # LOG: Minimal impact
    0.3,  # THROTTLE: Some disruption
    0.5,  # BLOCK: Significant impact
    0.8,  # ISOLATE: Major disruption
]


def get_action_cost(action: int) -> float:
    """Get the cost of a defensive action.

    Args:
        action: Action index (0-4).

    Returns:
        Cost of the action.
    """
    return ACTION_COSTS[action]


def _load_stage_detector(path: Path) -> Any:
    """Load a frozen stage detector from ``path``.

    Supports ``.pt`` (PyTorch :class:`StageDetector`) and ``.joblib``
    (sklearn :class:`RandomForestClassifier`) checkpoints.  Returns an
    object with a ``predict(features_2d) -> stage_ids`` method.
    """
    suffix = path.suffix.lower()
    if suffix == ".pt":
        from src.detector.stage_detector import StageDetector

        det = StageDetector.from_checkpoint(path)
        # wrap so caller sees uniform ``predict``
        return _DetectorWrapper(det.predict)
    if suffix in (".joblib", ".pkl", ".pickle"):
        import joblib

        clf = joblib.load(path)
        return _DetectorWrapper(clf.predict)
    raise ValueError(
        f"Unsupported stage-detector checkpoint format: {path} "
        f"(expected .pt or .joblib)"
    )


class _DetectorWrapper:
    """Thin wrapper unifying StageDetector.predict and sklearn.predict."""

    def __init__(self, predict_fn):
        self._predict = predict_fn

    def predict(self, X: np.ndarray) -> np.ndarray:
        return self._predict(X)


def get_action_name(action: int) -> str:
    """Get the name of a defensive action.

    Args:
        action: Action index (0-4).

    Returns:
        Name of the action.
    """
    return ACTION_NAMES[action]


# =============================================================================
# RECOMMENDED-ACTION MAPPING (IoTWarden-aligned, see PLAN §3.1 step 2)
# =============================================================================
#
# stage  -> recommended action
#  0  BENIGN     -> 0  OBSERVE
#  1  RECON      -> 1  LOG
#  2  ACCESS     -> 2  THROTTLE
#  3  MANEUVER   -> 3  BLOCK
#  4  IMPACT     -> 4  ISOLATE
#
# This is the canonical mapping used by IoTWarden (Bhattacharjee et al., 2023,
# Fig. 4) and the policy the new reward function grades against. An action
# within ±1 of the recommended level earns ``reward_proportional``; ±2 or
# more earns ``-penalty_disproportionate``.

_RECOMMENDED_ACTION_BY_STAGE: list[int] = [0, 1, 2, 3, 4]


def _recommended_action(stage: int) -> int:
    """Return the IoTWarden-aligned recommended action for ``stage``."""
    return _RECOMMENDED_ACTION_BY_STAGE[stage]


