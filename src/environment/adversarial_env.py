class AdversarialIoTEnv(gym.Env):
    """Gymnasium environment for adversarial IoT defense training.

    This environment implements a partially observable Markov decision
    process where the agent observes realized network features but
    cannot directly see the underlying attack stage.

        Attacker (first-order Markov chain):
        - Controls attack progression through Kill Chain stages
        - Samples kill-chain stage transitions from a first-order Markov chain

    Blue Team (RL Agent):
        - Observes window of feature vectors
        - Takes discrete defensive actions
        - Receives reward based on defense effectiveness

    Observation Space:
        Box of shape (window_size * num_features,) or
        (window_size * num_features * 2,) when delta features are enabled.

    Action Space:
        Discrete(5): OBSERVE, LOG, RESTRICT, BLOCK, ISOLATE

    Example:
        >>> env = AdversarialIoTEnv(dataset_path)
        >>> obs, info = env.reset()
        >>> obs, reward, terminated, truncated, info = env.step(2)

    .. warning::
       **Direct construction contract (Step-3 F2 / Step-8 doc-fix).**
       Calling ``AdversarialIoTEnv(dataset_path, ...)``
       directly builds a non-split-aware ``RealizationEngine`` (the
       constructor below instantiates ``RealizationEngine(
       dataset_path)`` with no ``split_manifest`` / ``allowed_indices``
       argument). This means the engine samples from the *full* row
       pool — it does NOT honour the dataset-prep OOD-exclusion or
        ``split="train"`` invariants the Stage Detector through Ablation & Robustness depend on.

       **Production callers must use one of**:

       - ``src.blue_team.env_factory.make_train_env(...)`` (sets
         ``split="train", exclude_ood=True`` and monkey-patches the
         engine post-construction via ``env._realization_engine =
         engine``); or
       - ``src.blue_team.env_factory.make_eval_env(...)`` (caller
         supplies the eval split — typically ``"val_balanced"`` for
          Blue-Team eval or ``"test_balanced"`` for benchmark / ablation).

       Direct ``AdversarialIoTEnv(...)`` construction is reserved for
       synthetic-data unit tests (see ``tests/test_adversarial_env.py``)
       and the hand-rolled smoke probe in
       ``scripts/benchmark/run_test_eval.py:_roll_deterministic`` (RF-
       Acting feature-dim probe). A future refactor could add an
       ``engine: Optional[RealizationEngine] = None`` injection seam
       to ``__init__`` so the factory could pass the engine in
       directly (eliminating the ``# type: ignore[attr-defined]``
       monkey-patch in ``env_factory.py``); deferred to post-thesis.
    """

    metadata = {"render_modes": ["human"]}

    def __init__(
        self,
        dataset_path: Union[str, Path],
        config: Optional[AdversarialEnvConfig] = None,
        render_mode: Optional[str] = None,
        device: str = "cpu",
    ) -> None:
        """Initialize the Adversarial Environment.

        Args:
            dataset_path: Path to processed dataset for realization.
            config: Environment configuration.
            render_mode: Rendering mode (optional).
            device: Device for realization/detector tensors (CPU-first).
        """
        super().__init__()

        self._config = config or AdversarialEnvConfig()
        self._render_mode = render_mode
        self._device = device

        # Attacker dynamics: first-order Markov chain over kill-chain stages.
        self._attacker = MarkovAttacker()

        # Load Realization Engine (for feature sampling)
        dataset_path = Path(dataset_path)
        self._realization_engine = RealizationEngine(dataset_path)

        # Get feature dimension from dataset
        self._num_features = self._realization_engine.num_features

        # Load optional frozen stage detector for stage-prediction ablation
        self._stage_detector: Any = None
        if self._config.stage_detector_path is not None:
            self._stage_detector = _load_stage_detector(Path(self._config.stage_detector_path))

        # Define observation space: flattened window of features (optionally with deltas)
        obs_multiplier = 2 if self._config.include_deltas else 1
        obs_dim = self._config.window_size * self._num_features * obs_multiplier
        if self._config.include_stage_pred:
            if self._stage_detector is None:
                raise ValueError("include_stage_pred=True requires stage_detector_path to be set")
            obs_dim += self._config.num_actions  # one-hot appended stage
        self.observation_space = spaces.Box(
            low=-np.inf,
            high=np.inf,
            shape=(obs_dim,),
            dtype=np.float32,
        )

        # Define action space: force continuum levels
        self.action_space = spaces.Discrete(self._config.num_actions)

        # Episode state (initialized in reset)
        self._step_count: int = 0
        self._current_attack_stage: int = 0
        self._attack_history: list[int] = []
        self._observation_window: list[np.ndarray] = []
        self._last_action: int = 0
        # Evasion-before-commit: did the defender just apply force this step?
        self._recent_block: bool = False
        self._rng: Optional[np.random.Generator] = None
        # environment-design: MTTC tracking & defender-driven de-escalation
        self._first_attack_step: Optional[int] = None
        self._compromise_step: Optional[int] = None
        self._defender_deescalations: int = 0
        # FPR-penalty accumulator (review 2.2 / Direction 6)
        self._benign_steps: int = 0
        self._benign_blocks: int = 0

        logger.info(
            f"AdversarialIoTEnv initialized: "
            f"obs_shape={self.observation_space.shape}, "
            f"actions={self._config.num_actions}, "
            f"features={self._num_features}"
        )

